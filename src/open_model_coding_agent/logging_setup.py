"""Structured JSON logs with request IDs (house standard).

One line per event on stdout. The contract every line stands under
(round 15 states it, and a test holds a full work-order journey to
it):

- the line is one JSON object carrying ``ts``, ``level``, ``event``,
  and ``request_id``;
- ``request_id`` is the id of the HTTP request being served, taken
  from the ``x-request-id`` header or generated by the API's
  middleware — or null when the event happens outside a request
  (startup reconciliation, the CLI, a fold computed in-process);
- the line names the entities the event touches by their ids —
  ``work_order_id``, ``run_id``, ``batch_id``, ``comparison_id``,
  ``challenge_id``, the template's name and version, ``profile_id``
  — whichever the event concerns, so an operator can follow one
  entity's whole story through the log.

Deliberately tiny — the audit table is the durable record; the log
is for operators watching the process.
"""

from __future__ import annotations

import contextvars
import json
import sys
from datetime import datetime, timezone

request_id_var: contextvars.ContextVar[str | None] = contextvars.ContextVar(
    "request_id", default=None
)


def log_event(event: str, **fields) -> None:
    record = {
        "ts": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "level": "INFO",
        "event": event,
        "request_id": request_id_var.get(),
    }
    record.update(fields)
    print(json.dumps(record), file=sys.stdout, flush=True)
